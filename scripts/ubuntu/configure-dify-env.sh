PLUGIN_STORAGE_LOCAL_ROOT=${PLUGIN_STORAGE}/storage
PLUGIN_INSTALLED_PATH=${PLUGIN_STORAGE}/plugin
PLUGIN_WORKING_PATH=${PLUGIN_STORAGE}/cwd
PERSISTENCE_STORAGE_PATH=${PLUGIN_STORAGE}/persistence

